-- ----------------------------------------------------------------------------
-- 1. DROP EXISTING OBJECTS (IDEMPOTENT EXECUTION)
-- ----------------------------------------------------------------------------
BEGIN
    FOR t IN (
        SELECT table_name FROM user_tables 
        WHERE table_name IN (
            'NOTIFICATIONS', 'NOTIFICATION_TEMPLATES', 'PROGRESS_UPDATES',
            'WORK_ORDERS', 'CREW_MEMBERS', 'CREWS', 'OUTAGE_REPORTS',
            'OUTAGES', 'CUSTOMERS', 'FEEDERS', 'AREAS', 'USER_ROLES',
            'USERS', 'ROLES'
        )
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ----------------------------------------------------------------------------
-- 2. ROLES TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE ROLES (
    ROLE_ID         NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NAME            VARCHAR2(50 CHAR) NOT NULL,
    DESCRIPTION     VARCHAR2(255 CHAR),
    CONSTRAINT UQ_ROLES_NAME UNIQUE (NAME)
);

-- ----------------------------------------------------------------------------
-- 3. USERS TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE USERS (
    USER_ID         NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USERNAME        VARCHAR2(50 CHAR) NOT NULL,
    EMAIL           VARCHAR2(100 CHAR) NOT NULL,
    PASSWORD        VARCHAR2(120 CHAR) NOT NULL,
    FULL_NAME       VARCHAR2(100 CHAR) NOT NULL,
    PHONE_NUMBER    VARCHAR2(20 CHAR),
    IS_ACTIVE       NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP,
    CONSTRAINT UQ_USERS_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CHK_USERS_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

-- ----------------------------------------------------------------------------
-- 4. USER_ROLES JOIN TABLE (MANY-TO-MANY)
-- ----------------------------------------------------------------------------
CREATE TABLE USER_ROLES (
    USER_ID         NUMBER(19) NOT NULL,
    ROLE_ID         NUMBER(10) NOT NULL,
    CONSTRAINT PK_USER_ROLES PRIMARY KEY (USER_ID, ROLE_ID),
    CONSTRAINT FK_UR_USER FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_UR_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES (ROLE_ID) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 5. AREAS TABLE (DISTRIBUTION ZONES)
-- ----------------------------------------------------------------------------
CREATE TABLE AREAS (
    AREA_ID         NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    AREA_CODE       VARCHAR2(20 CHAR) NOT NULL,
    AREA_NAME       VARCHAR2(100 CHAR) NOT NULL,
    REGION          VARCHAR2(50 CHAR) NOT NULL,
    CITY            VARCHAR2(50 CHAR) NOT NULL,
    TOTAL_CUSTOMERS NUMBER(10) DEFAULT 0 NOT NULL,
    IS_ACTIVE       NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_AREAS_CODE UNIQUE (AREA_CODE),
    CONSTRAINT CHK_AREAS_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

-- ----------------------------------------------------------------------------
-- 6. FEEDERS TABLE (ELECTRICAL DISTRIBUTION CIRCUITS / SUBSTATIONS)
-- ----------------------------------------------------------------------------
CREATE TABLE FEEDERS (
    FEEDER_ID       NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    FEEDER_CODE     VARCHAR2(50 CHAR) NOT NULL,
    FEEDER_NAME     VARCHAR2(100 CHAR) NOT NULL,
    AREA_ID         NUMBER(10) NOT NULL,
    SUBSTATION_NAME VARCHAR2(100 CHAR) NOT NULL,
    CAPACITY_KVA    NUMBER(10, 2) NOT NULL,
    VOLTAGE_LEVEL   VARCHAR2(20 CHAR) NOT NULL,
    STATUS          VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_FEEDERS_CODE UNIQUE (FEEDER_CODE),
    CONSTRAINT FK_FEEDER_AREA FOREIGN KEY (AREA_ID) REFERENCES AREAS (AREA_ID),
    CONSTRAINT CHK_FEEDER_STATUS CHECK (STATUS IN ('ACTIVE', 'TRIPPED', 'MAINTENANCE', 'DECOMMISSIONED'))
);

-- ----------------------------------------------------------------------------
-- 7. CUSTOMERS TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE CUSTOMERS (
    CUSTOMER_ID     NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USER_ID         NUMBER(19),
    ACCOUNT_NUMBER  VARCHAR2(50 CHAR) NOT NULL,
    FULL_NAME       VARCHAR2(100 CHAR) NOT NULL,
    PHONE_NUMBER    VARCHAR2(20 CHAR) NOT NULL,
    EMAIL           VARCHAR2(100 CHAR),
    SERVICE_ADDRESS VARCHAR2(255 CHAR) NOT NULL,
    METER_NUMBER    VARCHAR2(50 CHAR) NOT NULL,
    AREA_ID         NUMBER(10) NOT NULL,
    FEEDER_ID       NUMBER(10) NOT NULL,
    CUSTOMER_TYPE   VARCHAR2(30 CHAR) DEFAULT 'RESIDENTIAL' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_CUST_ACCOUNT UNIQUE (ACCOUNT_NUMBER),
    CONSTRAINT UQ_CUST_METER UNIQUE (METER_NUMBER),
    CONSTRAINT FK_CUST_USER FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID) ON DELETE SET NULL,
    CONSTRAINT FK_CUST_AREA FOREIGN KEY (AREA_ID) REFERENCES AREAS (AREA_ID),
    CONSTRAINT FK_CUST_FEEDER FOREIGN KEY (FEEDER_ID) REFERENCES FEEDERS (FEEDER_ID),
    CONSTRAINT CHK_CUST_TYPE CHECK (CUSTOMER_TYPE IN ('RESIDENTIAL', 'COMMERCIAL', 'INDUSTRIAL', 'CRITICAL_INFRASTRUCTURE'))
);

-- ----------------------------------------------------------------------------
-- 8. OUTAGES TABLE (CORE INCIDENT RECORDS)
-- ----------------------------------------------------------------------------
CREATE TABLE OUTAGES (
    OUTAGE_ID                   NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    OUTAGE_NUMBER               VARCHAR2(50 CHAR) NOT NULL,
    TITLE                       VARCHAR2(150 CHAR) NOT NULL,
    DESCRIPTION                 VARCHAR2(2000 CHAR),
    AREA_ID                     NUMBER(10) NOT NULL,
    FEEDER_ID                   NUMBER(10),
    SEVERITY                    VARCHAR2(20 CHAR) NOT NULL,
    STATUS                      VARCHAR2(20 CHAR) DEFAULT 'REPORTED' NOT NULL,
    OUTAGE_TYPE                 VARCHAR2(30 CHAR) DEFAULT 'UNPLANNED' NOT NULL,
    REPORTED_AT                 TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    VERIFIED_AT                 TIMESTAMP,
    ESTIMATED_RESTORE_TIME      TIMESTAMP,
    ACTUAL_RESTORE_TIME         TIMESTAMP,
    RESTORATION_DURATION_MINUTES NUMBER(10),
    AFFECTED_CUSTOMERS_COUNT    NUMBER(10) DEFAULT 1 NOT NULL,
    ROOT_CAUSE                  VARCHAR2(255 CHAR),
    LATITUDE                    NUMBER(9, 6),
    LONGITUDE                   NUMBER(9, 6),
    REPORT_COUNT                NUMBER(10) DEFAULT 1 NOT NULL,
    CREATED_BY                  NUMBER(19),
    CREATED_AT                  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT                  TIMESTAMP,
    CONSTRAINT UQ_OUTAGE_NUMBER UNIQUE (OUTAGE_NUMBER),
    CONSTRAINT FK_OUTAGE_AREA FOREIGN KEY (AREA_ID) REFERENCES AREAS (AREA_ID),
    CONSTRAINT FK_OUTAGE_FEEDER FOREIGN KEY (FEEDER_ID) REFERENCES FEEDERS (FEEDER_ID),
    CONSTRAINT FK_OUTAGE_CREATOR FOREIGN KEY (CREATED_BY) REFERENCES USERS (USER_ID),
    CONSTRAINT CHK_OUTAGE_SEV CHECK (SEVERITY IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT CHK_OUTAGE_STAT CHECK (STATUS IN ('REPORTED', 'VERIFIED', 'IN_PROGRESS', 'RESTORED', 'CANCELLED')),
    CONSTRAINT CHK_OUTAGE_TYPE CHECK (OUTAGE_TYPE IN ('UNPLANNED', 'PLANNED_MAINTENANCE', 'WEATHER_EVENT', 'EQUIPMENT_FAILURE'))
);

-- ----------------------------------------------------------------------------
-- 9. OUTAGE_REPORTS TABLE (INDIVIDUAL CUSTOMER/CALL-CENTER REPORTS)
-- ----------------------------------------------------------------------------
CREATE TABLE OUTAGE_REPORTS (
    REPORT_ID       NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    OUTAGE_ID       NUMBER(19),
    CUSTOMER_ID     NUMBER(19),
    REPORTER_NAME   VARCHAR2(100 CHAR) NOT NULL,
    CONTACT_PHONE   VARCHAR2(20 CHAR) NOT NULL,
    AREA_ID         NUMBER(10) NOT NULL,
    FEEDER_ID       NUMBER(10),
    DESCRIPTION     VARCHAR2(1000 CHAR),
    SEVERITY        VARCHAR2(20 CHAR) DEFAULT 'MEDIUM' NOT NULL,
    REPORT_SOURCE   VARCHAR2(20 CHAR) DEFAULT 'CUSTOMER_PORTAL' NOT NULL,
    REPORTED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    STATUS          VARCHAR2(20 CHAR) DEFAULT 'LOGGED' NOT NULL,
    CONSTRAINT FK_REP_OUTAGE FOREIGN KEY (OUTAGE_ID) REFERENCES OUTAGES (OUTAGE_ID) ON DELETE SET NULL,
    CONSTRAINT FK_REP_CUST FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS (CUSTOMER_ID) ON DELETE SET NULL,
    CONSTRAINT FK_REP_AREA FOREIGN KEY (AREA_ID) REFERENCES AREAS (AREA_ID),
    CONSTRAINT FK_REP_FEEDER FOREIGN KEY (FEEDER_ID) REFERENCES FEEDERS (FEEDER_ID),
    CONSTRAINT CHK_REP_SEV CHECK (SEVERITY IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT CHK_REP_SOURCE CHECK (REPORT_SOURCE IN ('CUSTOMER_PORTAL', 'CALL_CENTER', 'MOBILE_APP', 'SCADA_SYSTEM', 'SMS')),
    CONSTRAINT CHK_REP_STATUS CHECK (STATUS IN ('LOGGED', 'LINKED_TO_OUTAGE', 'DISMISSED'))
);

-- ----------------------------------------------------------------------------
-- 10. CREWS TABLE (FIELD RESTORATION TEAMS)
-- ----------------------------------------------------------------------------
CREATE TABLE CREWS (
    CREW_ID             NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CREW_CODE           VARCHAR2(30 CHAR) NOT NULL,
    CREW_NAME           VARCHAR2(100 CHAR) NOT NULL,
    LEAD_ENGINEER_ID    NUMBER(19),
    VEHICLE_NUMBER      VARCHAR2(30 CHAR) NOT NULL,
    VEHICLE_TYPE        VARCHAR2(50 CHAR) DEFAULT 'Bucket Truck' NOT NULL,
    CONTACT_PHONE       VARCHAR2(20 CHAR) NOT NULL,
    AVAILABILITY_STATUS VARCHAR2(20 CHAR) DEFAULT 'AVAILABLE' NOT NULL,
    BASE_AREA_ID        NUMBER(10) NOT NULL,
    MEMBERS_COUNT       NUMBER(5) DEFAULT 3 NOT NULL,
    SKILL_SPECIALIZATION VARCHAR2(100 CHAR) DEFAULT 'High Voltage Restoration',
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP,
    CONSTRAINT UQ_CREWS_CODE UNIQUE (CREW_CODE),
    CONSTRAINT FK_CREW_LEAD FOREIGN KEY (LEAD_ENGINEER_ID) REFERENCES USERS (USER_ID) ON DELETE SET NULL,
    CONSTRAINT FK_CREW_AREA FOREIGN KEY (BASE_AREA_ID) REFERENCES AREAS (AREA_ID),
    CONSTRAINT CHK_CREW_STATUS CHECK (AVAILABILITY_STATUS IN ('AVAILABLE', 'DISPATCHED', 'ON_DUTY', 'OFF_DUTY', 'MAINTENANCE'))
);

-- ----------------------------------------------------------------------------
-- 11. CREW_MEMBERS TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE CREW_MEMBERS (
    MEMBER_ID        NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CREW_ID          NUMBER(10) NOT NULL,
    USER_ID          NUMBER(19),
    MEMBER_NAME      VARCHAR2(100 CHAR) NOT NULL,
    ROLE_DESIGNATION VARCHAR2(50 CHAR) NOT NULL,
    PHONE            VARCHAR2(20 CHAR) NOT NULL,
    CREATED_AT       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_CM_CREW FOREIGN KEY (CREW_ID) REFERENCES CREWS (CREW_ID) ON DELETE CASCADE,
    CONSTRAINT FK_CM_USER FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID) ON DELETE SET NULL
);

-- ----------------------------------------------------------------------------
-- 12. WORK_ORDERS TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE WORK_ORDERS (
    WORK_ORDER_ID              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    WO_NUMBER                  VARCHAR2(50 CHAR) NOT NULL,
    OUTAGE_ID                  NUMBER(19) NOT NULL,
    CREW_ID                    NUMBER(10),
    PRIORITY                   VARCHAR2(20 CHAR) DEFAULT 'MEDIUM' NOT NULL,
    STATUS                     VARCHAR2(20 CHAR) DEFAULT 'CREATED' NOT NULL,
    ASSIGNED_AT                TIMESTAMP,
    DISPATCHED_AT              TIMESTAMP,
    ARRIVED_AT                 TIMESTAMP,
    COMPLETED_AT               TIMESTAMP,
    ESTIMATED_DURATION_MINUTES NUMBER(10),
    INSTRUCTIONS               VARCHAR2(2000 CHAR),
    RESOLUTION_NOTES           VARCHAR2(2000 CHAR),
    CREATED_BY                 NUMBER(19) NOT NULL,
    CREATED_AT                 TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT                 TIMESTAMP,
    CONSTRAINT UQ_WO_NUMBER UNIQUE (WO_NUMBER),
    CONSTRAINT FK_WO_OUTAGE FOREIGN KEY (OUTAGE_ID) REFERENCES OUTAGES (OUTAGE_ID),
    CONSTRAINT FK_WO_CREW FOREIGN KEY (CREW_ID) REFERENCES CREWS (CREW_ID),
    CONSTRAINT FK_WO_CREATOR FOREIGN KEY (CREATED_BY) REFERENCES USERS (USER_ID),
    CONSTRAINT CHK_WO_PRIORITY CHECK (PRIORITY IN ('LOW', 'MEDIUM', 'HIGH', 'EMERGENCY')),
    CONSTRAINT CHK_WO_STATUS CHECK (STATUS IN ('CREATED', 'ASSIGNED', 'EN_ROUTE', 'WORKING', 'COMPLETED', 'CANCELLED'))
);

-- ----------------------------------------------------------------------------
-- 13. PROGRESS_UPDATES TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE PROGRESS_UPDATES (
    UPDATE_ID                   NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    WORK_ORDER_ID               NUMBER(19) NOT NULL,
    OUTAGE_ID                   NUMBER(19) NOT NULL,
    ENGINEER_ID                 NUMBER(19) NOT NULL,
    PERCENTAGE_COMPLETE         NUMBER(3) NOT NULL,
    STATUS_REACHED              VARCHAR2(50 CHAR) NOT NULL,
    REMARKS                     VARCHAR2(2000 CHAR) NOT NULL,
    ESTIMATED_RESTORATION_TIME  TIMESTAMP,
    CREATED_AT                  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_PU_WO FOREIGN KEY (WORK_ORDER_ID) REFERENCES WORK_ORDERS (WORK_ORDER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_PU_OUTAGE FOREIGN KEY (OUTAGE_ID) REFERENCES OUTAGES (OUTAGE_ID),
    CONSTRAINT FK_PU_ENG FOREIGN KEY (ENGINEER_ID) REFERENCES USERS (USER_ID),
    CONSTRAINT CHK_PU_PERCENT CHECK (PERCENTAGE_COMPLETE BETWEEN 0 AND 100)
);

-- ----------------------------------------------------------------------------
-- 14. NOTIFICATION_TEMPLATES TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE NOTIFICATION_TEMPLATES (
    TEMPLATE_ID     NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    EVENT_CODE      VARCHAR2(50 CHAR) NOT NULL,
    EVENT_NAME      VARCHAR2(100 CHAR) NOT NULL,
    TITLE_TEMPLATE  VARCHAR2(200 CHAR) NOT NULL,
    BODY_TEMPLATE   VARCHAR2(1000 CHAR) NOT NULL,
    CHANNELS        VARCHAR2(50 CHAR) DEFAULT 'SMS,EMAIL,IN_APP' NOT NULL,
    IS_ACTIVE       NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_NOTIF_TMPL_CODE UNIQUE (EVENT_CODE),
    CONSTRAINT CHK_NOTIF_TMPL_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

-- ----------------------------------------------------------------------------
-- 15. NOTIFICATIONS TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE NOTIFICATIONS (
    NOTIFICATION_ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USER_ID         NUMBER(19),
    CUSTOMER_ID     NUMBER(19),
    OUTAGE_ID       NUMBER(19),
    AREA_ID         NUMBER(10),
    EVENT_TYPE      VARCHAR2(50 CHAR) NOT NULL,
    TITLE           VARCHAR2(200 CHAR) NOT NULL,
    MESSAGE         VARCHAR2(2000 CHAR) NOT NULL,
    CHANNEL         VARCHAR2(20 CHAR) DEFAULT 'IN_APP' NOT NULL,
    STATUS          VARCHAR2(20 CHAR) DEFAULT 'SENT' NOT NULL,
    SENT_AT         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    READ_AT         TIMESTAMP,
    CONSTRAINT FK_NOTIF_USER FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_NOTIF_CUST FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS (CUSTOMER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_NOTIF_OUTAGE FOREIGN KEY (OUTAGE_ID) REFERENCES OUTAGES (OUTAGE_ID) ON DELETE SET NULL,
    CONSTRAINT FK_NOTIF_AREA FOREIGN KEY (AREA_ID) REFERENCES AREAS (AREA_ID) ON DELETE SET NULL,
    CONSTRAINT CHK_NOTIF_CHANNEL CHECK (CHANNEL IN ('SMS', 'EMAIL', 'IN_APP', 'PUSH')),
    CONSTRAINT CHK_NOTIF_STATUS CHECK (STATUS IN ('QUEUED', 'SENT', 'FAILED', 'READ'))
);

-- ----------------------------------------------------------------------------
-- 16. PERFORMANCE INDEXES
-- ----------------------------------------------------------------------------
CREATE INDEX IDX_USERS_USERNAME ON USERS (USERNAME);
CREATE INDEX IDX_USERS_EMAIL ON USERS (EMAIL);

CREATE INDEX IDX_CUST_ACCOUNT ON CUSTOMERS (ACCOUNT_NUMBER);
CREATE INDEX IDX_CUST_AREA_FEEDER ON CUSTOMERS (AREA_ID, FEEDER_ID);
CREATE INDEX IDX_CUST_USER ON CUSTOMERS (USER_ID);

CREATE INDEX IDX_OUTAGES_STATUS ON OUTAGES (STATUS);
CREATE INDEX IDX_OUTAGES_AREA_STATUS ON OUTAGES (AREA_ID, STATUS);
CREATE INDEX IDX_OUTAGES_FEEDER ON OUTAGES (FEEDER_ID);
CREATE INDEX IDX_OUTAGES_SEVERITY ON OUTAGES (SEVERITY);
CREATE INDEX IDX_OUTAGES_REPORTED_AT ON OUTAGES (REPORTED_AT DESC);

CREATE INDEX IDX_REP_OUTAGE ON OUTAGE_REPORTS (OUTAGE_ID);
CREATE INDEX IDX_REP_AREA_FEEDER ON OUTAGE_REPORTS (AREA_ID, FEEDER_ID);
CREATE INDEX IDX_REP_STATUS ON OUTAGE_REPORTS (STATUS);

CREATE INDEX IDX_CREWS_STATUS ON CREWS (AVAILABILITY_STATUS);
CREATE INDEX IDX_CREWS_AREA ON CREWS (BASE_AREA_ID);

CREATE INDEX IDX_WO_OUTAGE ON WORK_ORDERS (OUTAGE_ID);
CREATE INDEX IDX_WO_CREW ON WORK_ORDERS (CREW_ID);
CREATE INDEX IDX_WO_STATUS ON WORK_ORDERS (STATUS);
CREATE INDEX IDX_WO_PRIORITY ON WORK_ORDERS (PRIORITY);

CREATE INDEX IDX_PU_WO ON PROGRESS_UPDATES (WORK_ORDER_ID);
CREATE INDEX IDX_PU_OUTAGE ON PROGRESS_UPDATES (OUTAGE_ID);
CREATE INDEX IDX_PU_CREATED_AT ON PROGRESS_UPDATES (CREATED_AT ASC);

CREATE INDEX IDX_NOTIF_USER_STAT ON NOTIFICATIONS (USER_ID, STATUS);
CREATE INDEX IDX_NOTIF_CUST ON NOTIFICATIONS (CUSTOMER_ID);
CREATE INDEX IDX_NOTIF_OUTAGE ON NOTIFICATIONS (OUTAGE_ID);
CREATE INDEX IDX_NOTIF_SENT_AT ON NOTIFICATIONS (SENT_AT DESC);

COMMIT;
